// Функция получения случайного элемента
function getRandomElement(arr) {
    return arr[Math.floor(Math.random() * arr.length)];
}

// Основная функция генерации
function generateStatement() {
    const prefix = getRandomElement(prefixes);
    const subject = getRandomElement(subjects);
    const verb = getRandomElement(verbs);
    const object = getRandomElement(objects);
    const suffix = getRandomElement(suffixes);

    // Сборка идеального предложения
    return `${prefix} ${subject} ${verb} ${object}${suffix}`;
}

// Функция для генерации хештегов
function generateHashtags() {
    // Берем 2 случайных разных хештега
    let tag1 = getRandomElement(hashtags);
    let tag2 = getRandomElement(hashtags);
    while (tag2 === tag1) {
        tag2 = getRandomElement(hashtags);
    }
    return `${tag1} ${tag2}`;
}

// Инициализация
document.addEventListener("DOMContentLoaded", () => {
    const btn = document.getElementById("generate-btn");
    const postText = document.getElementById("post-text");
    const tagsEl = document.getElementById("tags");

    btn.addEventListener("click", () => {
        // Обновляем текст
        postText.textContent = generateStatement();
        tagsEl.textContent = generateHashtags();
        
        // Перезапускаем анимацию появления
        postText.classList.remove("animate");
        tagsEl.classList.remove("animate");
        void postText.offsetWidth; // Принудительный reflow для сброса анимации
        void tagsEl.offsetWidth;
        postText.classList.add("animate");
        tagsEl.classList.add("animate");
    });
});